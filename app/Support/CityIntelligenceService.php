<?php
declare(strict_types=1);

namespace App\Support;

use DateTimeImmutable;
use DateTimeZone;
use PDO;
use Throwable;

/**
 * LOCUS-SF City Investment Intelligence & Reporting Service
 *
 * Dedicated executive municipal query engine for the City Assessor’s Office (CAO),
 * Local Economic & Business Development Office (LEBDO), and City Information &
 * Communications Technology Office (CICTO).
 *
 * Distinct from property-level IAI:
 *   - The IAI evaluates an individual parcel's recorded attractiveness based on 5 weighted criteria.
 *   - This service evaluates city-wide municipal inventory, listing velocity, broker capacity,
 *     investor engagement, and assessment readiness across San Fernando City, La Union.
 */
class CityIntelligenceService
{
    public const TIMEZONE = 'Asia/Manila';
    public const MUNICIPAL_HEADER = 'City Government of San Fernando, La Union | LOCUS-SF Investment Intelligence';
    public const MANDATORY_REPORT_FOOTER = 'Generated by LOCUS-SF | For planning and information purposes | Subject to data completeness and verification';

    private PDO $pdo;

    public function __construct(PDO $pdo)
    {
        $this->pdo = $pdo;
    }

    /**
     * Resolves date bounds from standard period codes or custom date inputs.
     */
    public function resolveDateBounds(string $range, ?string $customStart = null, ?string $customEnd = null): array
    {
        $tz = new DateTimeZone(self::TIMEZONE);
        $now = new DateTimeImmutable('now', $tz);

        return match ($range) {
            '30d' => [
                'start' => $now->modify('-30 days')->setTime(0, 0, 0),
                'end' => $now,
                'label' => 'Last 30 Days (' . $now->modify('-30 days')->format('M j, Y') . ' – ' . $now->format('M j, Y') . ')',
            ],
            '90d' => [
                'start' => $now->modify('-90 days')->setTime(0, 0, 0),
                'end' => $now,
                'label' => 'Last 90 Days (' . $now->modify('-90 days')->format('M j, Y') . ' – ' . $now->format('M j, Y') . ')',
            ],
            'ytd' => [
                'start' => $now->setDate((int) $now->format('Y'), 1, 1)->setTime(0, 0, 0),
                'end' => $now,
                'label' => 'Year-to-Date ' . $now->format('Y') . ' (Jan 1, ' . $now->format('Y') . ' – ' . $now->format('M j, Y') . ')',
            ],
            'custom' => (function () use ($customStart, $customEnd, $now, $tz) {
                $start = $customStart ? DateTimeImmutable::createFromFormat('Y-m-d', $customStart, $tz) : null;
                $end = $customEnd ? DateTimeImmutable::createFromFormat('Y-m-d', $customEnd, $tz) : null;
                $s = $start ? $start->setTime(0, 0, 0) : $now->modify('-365 days')->setTime(0, 0, 0);
                $e = $end ? $end->setTime(23, 59, 59) : $now;
                return [
                    'start' => $s,
                    'end' => $e,
                    'label' => 'Custom Period (' . $s->format('M j, Y') . ' – ' . $e->format('M j, Y') . ')',
                ];
            })(),
            default => [
                'start' => null,
                'end' => null,
                'label' => 'All Available Records (Cumulative)',
            ],
        };
    }

    /**
     * Build base SQL WHERE clauses and parameters for property queries.
     */
    private function buildPropertyFilterClauses(array $filters): array
    {
        $clauses = ['p.deleted_at IS NULL'];
        $params = [];

        // Date Range
        $bounds = $this->resolveDateBounds(
            (string) ($filters['date_range'] ?? 'all'),
            isset($filters['start_date']) ? (string) $filters['start_date'] : null,
            isset($filters['end_date']) ? (string) $filters['end_date'] : null
        );
        if ($bounds['start'] !== null) {
            $clauses[] = 'p.created_at >= :date_start';
            $params['date_start'] = $bounds['start']->format('Y-m-d H:i:s');
        }
        if ($bounds['end'] !== null) {
            $clauses[] = 'p.created_at <= :date_end';
            $params['date_end'] = $bounds['end']->format('Y-m-d H:i:s');
        }

        // Barangay filter
        $barangay = trim((string) ($filters['barangay'] ?? ''));
        if ($barangay !== '' && $barangay !== 'all') {
            $clauses[] = 'p.barangay = :barangay';
            $params['barangay'] = $barangay;
        }

        // Property Typology filter (Mutually exclusive primary form)
        $propertyType = trim((string) ($filters['property_type'] ?? ''));
        if ($propertyType !== '' && $propertyType !== 'all') {
            if ($propertyType === 'land') {
                $clauses[] = "(LOWER(p.category) LIKE '%land%' OR LOWER(p.type) LIKE '%lot%' OR LOWER(p.category) = 'land')";
            } elseif ($propertyType === 'building') {
                $clauses[] = "(LOWER(p.category) LIKE '%building%' OR LOWER(p.type) LIKE '%building%' OR LOWER(p.type) IN ('office', 'commercial building', 'warehouse', 'bpo'))";
            } elseif ($propertyType === 'mixed') {
                $clauses[] = "(NOT (LOWER(p.category) LIKE '%land%' OR LOWER(p.type) LIKE '%lot%' OR LOWER(p.category) = 'land') AND NOT (LOWER(p.category) LIKE '%building%' OR LOWER(p.type) LIKE '%building%' OR LOWER(p.type) IN ('office', 'commercial building', 'warehouse', 'bpo')))";
            }
        }

        // Status filter
        $status = trim((string) ($filters['status'] ?? ''));
        if ($status !== '' && $status !== 'all') {
            if ($status === 'published') {
                $clauses[] = "p.approval_state = 'approved' AND p.status = 'Available'";
            } elseif ($status === 'pending_review') {
                $clauses[] = "p.approval_state = 'pending_review'";
            } elseif ($status === 'draft') {
                $clauses[] = "p.approval_state = 'draft'";
            } elseif ($status === 'archived') {
                $clauses[] = "p.approval_state = 'archived'";
            }
        }

        return [
            'where' => implode(' AND ', $clauses),
            'params' => $params,
            'bounds' => $bounds,
        ];
    }

    /**
     * Compiles complete executive analytics across all 5 dimensions.
     */
    public function getDashboardData(array $filters = [], ?array $actor = null): array
    {
        $filtered = $this->buildPropertyFilterClauses($filters);
        $whereSql = $filtered['where'];
        $params = $filtered['params'];
        $bounds = $filtered['bounds'];

        $now = new DateTimeImmutable('now', new DateTimeZone(self::TIMEZONE));

        // 1. KPI Aggregates
        $kpi = $this->queryKpiSummary($whereSql, $params, $bounds);

        // 2. Property Inventory & Classification
        $inventory = $this->queryInventoryBreakdown($whereSql, $params);

        // 3. Listing Activity & Trends
        $activity = $this->queryListingActivity($whereSql, $params, $bounds);

        // 4. Broker Activity & Applications
        $brokers = $this->queryBrokerActivity($bounds);

        // 5. Investor Engagement & Interest
        $engagement = $this->queryInvestorEngagement($whereSql, $params);

        // 6. Assessment Readiness & MCE Verification
        $assessment = $this->queryAssessmentReadiness($whereSql, $params);

        $meta = [
            'system' => 'LOCUS-SF City Investment Intelligence & Reporting',
            'jurisdiction' => 'San Fernando City, La Union',
            'municipal_header' => self::MUNICIPAL_HEADER,
            'mandatory_footer' => self::MANDATORY_REPORT_FOOTER,
            'generated_at' => $now->format('Y-m-d H:i:s'),
            'generated_at_formatted' => $now->format('F j, Y, g:i A T'),
            'reporting_period' => $bounds['label'],
            'bounds' => $bounds,
            'filters' => $filters,
            'date_range_code' => (string) ($filters['date_range'] ?? 'all'),
            'filtered_barangay' => (string) ($filters['barangay'] ?? 'all'),
            'filtered_property_type' => (string) ($filters['property_type'] ?? 'all'),
            'filtered_status' => (string) ($filters['status'] ?? 'all'),
            'actor_department' => $actor['department'] ?? 'CICTO',
            'actor_name' => $actor['name'] ?? 'City Personnel',
        ];

        return [
            'meta' => $meta,
            'metadata' => $meta,
            'kpi' => $kpi,
            'kpis' => $kpi,
            'inventory' => $inventory,
            'listing_activity' => $activity,
            'activity' => $activity,
            'broker_activity' => $brokers,
            'brokers' => $brokers,
            'investor_engagement' => $engagement,
            'engagement' => $engagement,
            'assessment_readiness' => $assessment,
        ];
    }

    /**
     * KPI Summary query
     */
    public function queryKpiSummary(string $whereSql, array $params, array $bounds): array
    {
        $sql = "SELECT
            COUNT(*) as total_properties,
            SUM(CASE WHEN p.approval_state = 'approved' AND p.status = 'Available' THEN 1 ELSE 0 END) as published_available,
            SUM(CASE WHEN p.approval_state = 'pending_review' THEN 1 ELSE 0 END) as pending_review,
            SUM(CASE WHEN p.approval_state = 'archived' THEN 1 ELSE 0 END) as archived_count,
            SUM(CASE WHEN p.approval_state = 'draft' THEN 1 ELSE 0 END) as draft_count,
            SUM(CASE WHEN p.status IN ('Reserved', 'Sold') THEN 1 ELSE 0 END) as reserved_sold_count,
            COALESCE(SUM(p.area), 0) as total_land_area_sqm,
            COALESCE(AVG(p.area), 0) as avg_land_area_sqm,
            COALESCE(SUM(CASE WHEN LOWER(p.category) LIKE '%building%' OR LOWER(p.type) IN ('office', 'commercial building', 'warehouse', 'bpo') THEN p.area ELSE 0 END), 0) as total_building_area_sqm,
            COALESCE(SUM(CASE WHEN p.listing_purpose = 'sale' OR p.listing_purpose IS NULL THEN p.price ELSE 0 END), 0) as total_sale_volume_php
        FROM properties p
        WHERE {$whereSql}";

        $stmt = $this->pdo->prepare($sql);
        $stmt->execute($params);
        $row = $stmt->fetch(PDO::FETCH_ASSOC) ?: [];

        // Broker applications in period
        $brokerParams = [];
        $brokerWhere = '1=1';
        if ($bounds['start'] !== null) {
            $brokerWhere .= ' AND created_at >= :b_start';
            $brokerParams['b_start'] = $bounds['start']->format('Y-m-d H:i:s');
        }
        if ($bounds['end'] !== null) {
            $brokerWhere .= ' AND created_at <= :b_end';
            $brokerParams['b_end'] = $bounds['end']->format('Y-m-d H:i:s');
        }

        $bStmt = $this->pdo->prepare("SELECT COUNT(*) FROM seller_profiles WHERE {$brokerWhere}");
        $bStmt->execute($brokerParams);
        $brokerAppsInPeriod = (int) $bStmt->fetchColumn();

        // Investor high-intent signals (shortlists, inquiries, logged visits)
        $shortlistCount = (int) $this->pdo->query('SELECT COUNT(*) FROM property_shortlists')->fetchColumn();
        $inquiryCount = (int) $this->pdo->query('SELECT COUNT(*) FROM property_messages')->fetchColumn();
        $siteVisitsCount = (int) $this->pdo->query('SELECT COUNT(*) FROM visit_logs')->fetchColumn();

        $totalProps = (int) ($row['total_properties'] ?? 0);
        $published = (int) ($row['published_available'] ?? 0);
        $pending = (int) ($row['pending_review'] ?? 0);

        return [
            'total_properties' => $totalProps,
            'properties_total' => $totalProps,
            'published_available' => $published,
            'properties_published' => $published,
            'pending_review' => $pending,
            'properties_pending' => $pending,
            'archived_count' => (int) ($row['archived_count'] ?? 0),
            'draft_count' => (int) ($row['draft_count'] ?? 0),
            'reserved_sold_count' => (int) ($row['reserved_sold_count'] ?? 0),
            'submissions_in_period' => $totalProps,
            'total_land_area_sqm' => (float) ($row['total_land_area_sqm'] ?? 0),
            'avg_land_area_sqm' => round((float) ($row['avg_land_area_sqm'] ?? 0), 1),
            'total_building_area_sqm' => (float) ($row['total_building_area_sqm'] ?? 0),
            'total_sale_volume_php' => (float) ($row['total_sale_volume_php'] ?? 0),
            'broker_applications_in_period' => $brokerAppsInPeriod,
            'broker_applications_period' => $brokerAppsInPeriod,
            'total_shortlists' => $shortlistCount,
            'investor_shortlists_count' => $shortlistCount,
            'total_inquiries' => $inquiryCount,
            'investor_inquiries_count' => $inquiryCount,
            'total_site_visits' => $siteVisitsCount,
            'scheduled_site_visits_count' => $siteVisitsCount,
        ];
    }

    /**
     * Category, primary physical type, barangay, and tenure distribution.
     * Prevents double-counting between primary physical form and overlapping classifications.
     */
    public function queryInventoryBreakdown(string $whereSql, array $params): array
    {
        // 1. Primary Physical Types (Mutually Exclusive)
        $primaryTypesSql = "SELECT
            CASE
                WHEN LOWER(p.category) LIKE '%land%' OR LOWER(p.type) LIKE '%lot%' OR LOWER(p.category) = 'land' THEN 'Land Parcels'
                WHEN LOWER(p.category) LIKE '%building%' OR LOWER(p.type) LIKE '%building%' OR LOWER(p.type) IN ('office', 'commercial building', 'warehouse', 'bpo') THEN 'Buildings & Built Structures'
                ELSE 'Mixed / Unspecified Parcels'
            END as primary_type,
            COUNT(*) as count,
            COALESCE(SUM(p.area), 0) as total_area_sqm
        FROM properties p
        WHERE {$whereSql}
        GROUP BY primary_type
        ORDER BY count DESC";

        $ptStmt = $this->pdo->prepare($primaryTypesSql);
        $ptStmt->execute($params);
        $primaryTypesList = $ptStmt->fetchAll(PDO::FETCH_ASSOC);

        $primaryDict = [
            'land' => 0,
            'building' => 0,
            'mixed' => 0,
        ];
        foreach ($primaryTypesList as $pt) {
            if ($pt['primary_type'] === 'Land Parcels') {
                $primaryDict['land'] = (int) $pt['count'];
            } elseif ($pt['primary_type'] === 'Buildings & Built Structures') {
                $primaryDict['building'] = (int) $pt['count'];
            } else {
                $primaryDict['mixed'] += (int) $pt['count'];
            }
        }

        // 2. Overlapping Functional Classifications (Reported separately without double-counting totals)
        $rawRowsStmt = $this->pdo->prepare("SELECT p.type, p.category, p.subcategory, p.zoning_classification, p.tags_json FROM properties p WHERE {$whereSql}");
        $rawRowsStmt->execute($params);
        $rawProps = $rawRowsStmt->fetchAll(PDO::FETCH_ASSOC);

        $classCounts = [
            'commercial' => 0,
            'industrial' => 0,
            'residential' => 0,
            'agricultural' => 0,
            'special' => 0,
        ];

        foreach ($rawProps as $p) {
            $blob = strtolower(implode(' ', [
                (string) ($p['type'] ?? ''),
                (string) ($p['category'] ?? ''),
                (string) ($p['subcategory'] ?? ''),
                (string) ($p['zoning_classification'] ?? ''),
                (string) ($p['tags_json'] ?? ''),
            ]));

            if (str_contains($blob, 'commercial')) { $classCounts['commercial']++; }
            if (str_contains($blob, 'industrial') || str_contains($blob, 'warehouse') || str_contains($blob, 'logistics') || str_contains($blob, 'manufacturing')) { $classCounts['industrial']++; }
            if (str_contains($blob, 'residential') || str_contains($blob, 'housing')) { $classCounts['residential']++; }
            if (str_contains($blob, 'agricultural') || str_contains($blob, 'farming') || str_contains($blob, 'agr-s')) { $classCounts['agricultural']++; }
            if (str_contains($blob, 'mixed') || str_contains($blob, 'special') || str_contains($blob, 'pdz') || str_contains($blob, 'tourism') || str_contains($blob, 'hospitality')) { $classCounts['special']++; }
        }

        // 3. Listing Purpose (Tenure / Transaction Mode)
        $tenureSql = "SELECT
            CASE
                WHEN p.listing_purpose = 'lease' THEN 'lease'
                WHEN p.listing_purpose = 'both' THEN 'sale'
                WHEN p.listing_purpose = 'joint_venture' THEN 'joint_venture'
                WHEN p.listing_purpose = 'build_to_suit' THEN 'build_to_suit'
                ELSE 'sale'
            END as tenure_key,
            COUNT(*) as count
        FROM properties p
        WHERE {$whereSql}
        GROUP BY tenure_key";

        $tenureStmt = $this->pdo->prepare($tenureSql);
        $tenureStmt->execute($params);
        $tenureRows = $tenureStmt->fetchAll(PDO::FETCH_ASSOC);
        $tenureDict = [
            'sale' => 0,
            'lease' => 0,
            'joint_venture' => 0,
            'build_to_suit' => 0,
        ];
        foreach ($tenureRows as $tr) {
            $tenureDict[$tr['tenure_key']] = (int) $tr['count'];
        }

        // 4. Barangay Geographical Distribution (All official barangays accounted for)
        $rawBarangays = PropertyCatalog::barangays();
        $catalogBarangays = array_keys($rawBarangays);
        if (empty($catalogBarangays) || is_int(array_key_first($rawBarangays))) {
            $catalogBarangays = array_values($rawBarangays);
        }

        $bgySql = "SELECT
            COALESCE(NULLIF(TRIM(p.barangay), ''), 'Unspecified Barangay') as barangay,
            COUNT(*) as total_recorded,
            SUM(CASE WHEN p.approval_state = 'approved' AND p.status = 'Available' THEN 1 ELSE 0 END) as published_available,
            SUM(CASE WHEN p.approval_state = 'pending_review' THEN 1 ELSE 0 END) as pending_review,
            COALESCE(SUM(p.area), 0) as total_land_area_sqm,
            COALESCE(AVG(CASE WHEN p.price_per_sqm > 0 THEN p.price_per_sqm ELSE NULL END), 0) as avg_price_sqm
        FROM properties p
        WHERE {$whereSql}
        GROUP BY barangay";

        $bgyStmt = $this->pdo->prepare($bgySql);
        $bgyStmt->execute($params);
        $bgyRaw = $bgyStmt->fetchAll(PDO::FETCH_ASSOC);
        $bgyMap = [];
        foreach ($bgyRaw as $b) {
            $bgyMap[$b['barangay']] = $b;
        }

        $allBarangays = [];
        foreach ($catalogBarangays as $bgItem) {
            $bgName = is_array($bgItem) ? ($bgItem['name'] ?? 'Unknown') : (string) $bgItem;
            if (isset($bgyMap[$bgName])) {
                $rec = $bgyMap[$bgName];
                $allBarangays[] = [
                    'barangay' => $bgName,
                    'total_recorded' => (int) $rec['total_recorded'],
                    'published_available' => (int) $rec['published_available'],
                    'pending_review' => (int) $rec['pending_review'],
                    'total_land_area_sqm' => round((float) $rec['total_land_area_sqm'], 1),
                    'avg_price_sqm' => (float) $rec['avg_price_sqm'] > 0 ? round((float) $rec['avg_price_sqm']) : null,
                ];
            } else {
                $allBarangays[] = [
                    'barangay' => $bgName,
                    'total_recorded' => 0,
                    'published_available' => 0,
                    'pending_review' => 0,
                    'total_land_area_sqm' => 0.0,
                    'avg_price_sqm' => null,
                ];
            }
        }
        // Sort with populated barangays on top, then alphabetical
        usort($allBarangays, static function ($a, $b) {
            if ($b['total_recorded'] !== $a['total_recorded']) {
                return $b['total_recorded'] <=> $a['total_recorded'];
            }
            return strcasecmp($a['barangay'], $b['barangay']);
        });

        return [
            'primary_types' => $primaryDict,
            'primary_types_list' => $primaryTypesList,
            'classifications' => $classCounts,
            'tenure' => $tenureDict,
            'barangays' => $allBarangays,
            'barangay_distribution' => $allBarangays,
            'note_double_counting' => 'Primary property types are mutually exclusive physical forms. Functional classifications reflect recorded uses and may overlap without inflating inventory totals.',
        ];
    }

    /**
     * Submission vs Publication Trends, Review Queue Health.
     */
    public function queryListingActivity(string $whereSql, array $params, array $bounds): array
    {
        // Status Distribution
        $statusSql = "SELECT
            p.approval_state,
            COUNT(*) as count
        FROM properties p
        WHERE {$whereSql}
        GROUP BY p.approval_state";

        $stStmt = $this->pdo->prepare($statusSql);
        $stStmt->execute($params);
        $statusRows = $stStmt->fetchAll(PDO::FETCH_ASSOC);

        $statusDict = [
            'published' => 0,
            'pending_review' => 0,
            'draft' => 0,
            'archived' => 0,
        ];
        foreach ($statusRows as $sr) {
            $state = (string) $sr['approval_state'];
            if ($state === 'approved') {
                $statusDict['published'] = (int) $sr['count'];
            } elseif (isset($statusDict[$state])) {
                $statusDict[$state] = (int) $sr['count'];
            }
        }

        // Historical Submissions Trend
        $trendSql = "SELECT
            DATE_FORMAT(p.created_at, '%Y-%m') as period_key,
            DATE_FORMAT(p.created_at, '%b %Y') as period_label,
            COUNT(*) as submissions_count
        FROM properties p
        WHERE {$whereSql}
        GROUP BY period_key, period_label
        ORDER BY period_key ASC";

        $tStmt = $this->pdo->prepare($trendSql);
        $tStmt->execute($params);
        $submissionsTrend = $tStmt->fetchAll(PDO::FETCH_ASSOC);

        // Historical Publication / Approval Trend from audit_logs
        $auditSql = "SELECT
            DATE_FORMAT(a.created_at, '%Y-%m') as period_key,
            COUNT(*) as approvals_count
        FROM audit_logs a
        WHERE a.action_type = 'APPROVE' AND a.entity_type = 'PROPERTY'
        GROUP BY period_key
        ORDER BY period_key ASC";

        $approvalsMap = [];
        try {
            $aStmt = $this->pdo->query($auditSql);
            while ($ar = $aStmt->fetch(PDO::FETCH_ASSOC)) {
                $approvalsMap[$ar['period_key']] = (int) $ar['approvals_count'];
            }
        } catch (Throwable) {
            // Handled gracefully if empty
        }

        $timeline = [];
        foreach ($submissionsTrend as $sub) {
            $key = $sub['period_key'];
            $timeline[] = [
                'period_key' => $key,
                'period_label' => $sub['period_label'],
                'submissions' => (int) $sub['submissions_count'],
                'publications' => $approvalsMap[$key] ?? 0,
            ];
        }

        // Recent Submissions
        $recentSql = "SELECT
            p.id,
            p.name as title,
            p.barangay,
            p.approval_state as status,
            p.created_at
        FROM properties p
        WHERE {$whereSql}
        ORDER BY p.created_at DESC
        LIMIT 6";

        $rStmt = $this->pdo->prepare($recentSql);
        $rStmt->execute($params);
        $recentSubmissions = $rStmt->fetchAll(PDO::FETCH_ASSOC);

        return [
            'status_breakdown' => $statusDict,
            'status_distribution' => $statusDict,
            'timeline' => $timeline,
            'timeline_trends' => $timeline,
            'recent_submissions' => $recentSubmissions,
        ];
    }

    /**
     * Broker Application Pipeline & Licensing Integrity.
     */
    public function queryBrokerActivity(array $bounds): array
    {
        $bWhere = '1=1';
        $bParams = [];
        if ($bounds['start'] !== null) {
            $bWhere .= ' AND created_at >= :start';
            $bParams['start'] = $bounds['start']->format('Y-m-d H:i:s');
        }
        if ($bounds['end'] !== null) {
            $bWhere .= ' AND created_at <= :end';
            $bParams['end'] = $bounds['end']->format('Y-m-d H:i:s');
        }

        $stmt = $this->pdo->prepare("SELECT
            application_status,
            COUNT(*) as count
        FROM seller_profiles
        WHERE {$bWhere}
        GROUP BY application_status");
        $stmt->execute($bParams);
        $statuses = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $statusCounts = [
            'approved' => 0,
            'pending_review' => 0,
            'under_review' => 0,
            'requires_correction' => 0,
        ];
        foreach ($statuses as $s) {
            $key = (string) $s['application_status'];
            if ($key === 'verified' || $key === 'approved') {
                $statusCounts['approved'] += (int) $s['count'];
            } elseif ($key === 'pending_review' || $key === 'submitted') {
                $statusCounts['pending_review'] += (int) $s['count'];
            } elseif ($key === 'under_review') {
                $statusCounts['under_review'] += (int) $s['count'];
            } elseif ($key === 'requires_correction' || $key === 'rejected') {
                $statusCounts['requires_correction'] += (int) $s['count'];
            }
        }

        // Recent applications with STRICT privacy shielding (no PRC IDs, no TINs, no document paths)
        $recStmt = $this->pdo->prepare("SELECT
            COALESCE(NULLIF(TRIM(sp.display_name), ''), NULLIF(TRIM(sp.legal_name), ''), NULLIF(TRIM(sp.company_name), ''), 'Broker Applicant') as applicant_name,
            COALESCE(NULLIF(TRIM(sp.barangay), ''), 'San Fernando') as barangay,
            sp.application_status as status,
            sp.created_at
        FROM seller_profiles sp
        WHERE {$bWhere}
        ORDER BY sp.created_at DESC
        LIMIT 6");
        $recStmt->execute($bParams);
        $recentApps = $recStmt->fetchAll(PDO::FETCH_ASSOC);

        return [
            'summary' => [
                'total_applications' => array_sum($statusCounts),
                'approved' => $statusCounts['approved'],
                'pending' => $statusCounts['pending_review'],
            ],
            'status_breakdown' => $statusCounts,
            'recent_applications' => $recentApps,
            'privacy_notice' => 'Broker compliance metrics reflect administrative review states only. Personal credentials, PRC identity scans, and contact data are strictly excluded from reporting.',
        ];
    }

    /**
     * Investor Interest & High-Intent Engagement.
     */
    public function queryInvestorEngagement(string $whereSql, array $params): array
    {
        // 1. Most Shortlisted Properties
        $shortlistSql = "SELECT
            p.id,
            p.name as title,
            p.barangay,
            p.price,
            p.score,
            COUNT(s.id) as shortlists_count,
            (SELECT COUNT(*) FROM property_messages m WHERE m.property_id = p.id) as inquiries_count,
            (SELECT COUNT(*) FROM visit_logs v WHERE v.property_id = p.id) as site_visits_count
        FROM property_shortlists s
        JOIN properties p ON s.property_id = p.id
        WHERE {$whereSql}
        GROUP BY p.id, p.name, p.barangay, p.price, p.score
        ORDER BY shortlists_count DESC, inquiries_count DESC
        LIMIT 5";

        $slStmt = $this->pdo->prepare($shortlistSql);
        $slStmt->execute($params);
        $topShortlisted = $slStmt->fetchAll(PDO::FETCH_ASSOC);

        // Fallback: if no shortlists yet, fetch top properties
        if (empty($topShortlisted)) {
            $fallbackSql = "SELECT
                p.id,
                p.name as title,
                p.barangay,
                p.price,
                p.score,
                (SELECT COUNT(*) FROM property_shortlists s WHERE s.property_id = p.id) as shortlists_count,
                (SELECT COUNT(*) FROM property_messages m WHERE m.property_id = p.id) as inquiries_count,
                (SELECT COUNT(*) FROM visit_logs v WHERE v.property_id = p.id) as site_visits_count
            FROM properties p
            WHERE {$whereSql}
            ORDER BY shortlists_count DESC, p.created_at DESC
            LIMIT 5";
            $fbStmt = $this->pdo->prepare($fallbackSql);
            $fbStmt->execute($params);
            $topShortlisted = $fbStmt->fetchAll(PDO::FETCH_ASSOC);
        }

        $shortlistTotal = (int) $this->pdo->query('SELECT COUNT(*) FROM property_shortlists')->fetchColumn();
        $inquiryTotal = (int) $this->pdo->query('SELECT COUNT(*) FROM property_messages')->fetchColumn();
        $visitTotal = (int) $this->pdo->query('SELECT COUNT(*) FROM visit_logs')->fetchColumn();

        return [
            'telemetry_status' => [
                'event_logging' => 'high_intent_actions_only',
                'property_views_instrumentation' => 'pending_dedicated_telemetry',
                'disclosure' => 'Property-specific pageview telemetry requires dedicated client-side logging. To maintain municipal data authenticity, this module currently reports verified high-intent investor actions (saved shortlists, inquiries, and site visits) without conflating them with general website visit counts.',
            ],
            'signals' => [
                'shortlists' => $shortlistTotal,
                'inquiries' => $inquiryTotal,
                'site_visits' => $visitTotal,
            ],
            'top_shortlisted_properties' => $topShortlisted,
            'privacy_notice' => 'Individual investor browsing identities and saved folder contents are strictly shielded to protect investor privacy.',
        ];
    }

    /**
     * Assessment Readiness & MCE Verification Methodology Summary.
     */
    public function queryAssessmentReadiness(string $whereSql, array $params): array
    {
        $sql = "SELECT
            p.id,
            p.name as title,
            p.barangay,
            p.score as iai_score,
            p.approval_state as status,
            p.zoning_classification,
            p.clup_verified_at,
            p.site_verified_at,
            p.documents_reviewed_at,
            p.automatic_assessment_json
        FROM properties p
        WHERE {$whereSql}
        ORDER BY p.id ASC";

        $stmt = $this->pdo->prepare($sql);
        $stmt->execute($params);
        $rows = $stmt->fetchAll(PDO::FETCH_ASSOC);

        $counts = [
            'complete_verified' => 0,
            'provisional_model' => 0,
            'incomplete_criteria' => 0,
        ];

        $clupZoning = [
            'verified_compliant' => 0,
            'pending_verification' => 0,
            'conditional_exception' => 0,
            'zoning_incompatible' => 0,
        ];

        $hazardFlags = [
            'flood_prone' => 0,
            'steep_slope' => 0,
            'fault_proximity' => 0,
            'clear' => 0,
        ];

        $queue = [];

        foreach ($rows as $r) {
            $auto = json_decode((string) ($r['automatic_assessment_json'] ?? ''), true);
            $isComplete = !empty($auto['assessmentComplete']);
            $hasScore = ($r['iai_score'] !== null && (float) $r['iai_score'] > 0);
            $hasSiteVer = !empty($r['site_verified_at']);
            $hasClupVer = !empty($r['clup_verified_at']);

            $isCompleteVerified = ($isComplete && $hasSiteVer);
            $isProvisional = (!$isCompleteVerified && ($hasScore || !empty($auto['completedCount'])));

            if ($isCompleteVerified) {
                $counts['complete_verified']++;
            } elseif ($isProvisional) {
                $counts['provisional_model']++;
            } else {
                $counts['incomplete_criteria']++;
            }

            // Zoning status
            $zoningState = 'pending_verification';
            if ($hasClupVer) {
                $zoningState = 'verified_compliant';
                $clupZoning['verified_compliant']++;
            } elseif (!empty($r['zoning_classification'])) {
                $clupZoning['pending_verification']++;
            } else {
                $clupZoning['pending_verification']++;
            }

            // Hazard flags check
            $inputs = $auto['inputs'] ?? [];
            $hasHazard = false;
            if (!empty($inputs['flood_susceptibility']) && in_array($inputs['flood_susceptibility'], ['high', 'frequent', 'critical'], true)) {
                $hazardFlags['flood_prone']++;
                $hasHazard = true;
            }
            if (!empty($inputs['fault_line_proximity']) && in_array($inputs['fault_line_proximity'], ['within_buffer', 'active_fault', 'critical'], true)) {
                $hazardFlags['fault_proximity']++;
                $hasHazard = true;
            }
            if (!$hasHazard) {
                $hazardFlags['clear']++;
            }

            $queue[] = [
                'id' => (int) $r['id'],
                'title' => (string) $r['title'],
                'barangay' => (string) ($r['barangay'] ?? 'San Fernando'),
                'iai_score' => $r['iai_score'] !== null ? round((float) $r['iai_score'], 2) : null,
                'status' => (string) $r['status'],
                'is_complete' => $isCompleteVerified,
                'is_provisional' => $isProvisional,
                'zoning_status' => $hasClupVer ? 'Verified Compliant' : 'Pending Verification',
                'has_hazard_flag' => $hasHazard,
            ];
        }

        return [
            'counts' => $counts,
            'readiness_counts' => $counts,
            'clup_zoning' => $clupZoning,
            'hazard_review_flags' => $hazardFlags,
            'readiness_queue' => array_slice($queue, 0, 8),
            'methodological_distinction' => 'Multi-Criteria Evaluation (MCE) and Investment Attractiveness Index (IAI) scores are comparative decision-support metrics calculated from verified site evidence and published benchmarks. They do not constitute statutory tax appraisals or transactional endorsements.',
        ];
    }
